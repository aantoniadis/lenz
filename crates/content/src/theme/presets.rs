pub fn builtin(id: &str) -> Option<&'static Palette> {
    match id {
        "darcula" => Some(&super::DARCULA),
        "light" => Some(&super::LIGHT),
        "catppuccin" => Some(&CATPPUCCIN),
        "catppuccin-latte" => Some(&LATTE),
        "tokyo-night" => Some(&TOKYO),
        "gruvbox" => Some(&GRUVBOX),
        "nord" => Some(&NORD),
        "everforest" => Some(&EVERFOREST),
        "kanagawa" => Some(&KANAGAWA),
        "dracula" => Some(&DRACULA),
        "one-dark" => Some(&ONE_DARK),
        "rose-pine" => Some(&ROSE_PINE),
        "rose-pine-dawn" => Some(&ROSE_PINE_DAWN),
        "flexoki-light" => Some(&FLEXOKI_LIGHT),
        "solarized-light" => Some(&SOLARIZED_LIGHT),
        "github-light" => Some(&GITHUB_LIGHT),
        _ => None,
    }
}
pub fn builtin_entries() -> Vec<ThemeEntry> {
    BUILTINS
        .iter()
        .map(|(id, label)| ThemeEntry {
            id: (*id).into(),
            label: (*label).into(),
            palette: std::sync::Arc::new(*builtin(id).unwrap()),
        })
        .collect()
}
