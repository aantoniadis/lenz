//! Base palettes from Omarchy and upstream editor themes; sources and MIT notices in docs/themes.md.
use super::{Palette, Syntax, ThemeEntry};
#[derive(Clone, Copy)]
pub(super) struct Seed {
    pub bg: u32,
    pub fg: u32,
    pub accent: u32,
    pub selection: u32,
    pub muted: u32,
    pub dark: u32,
    pub lighter: u32,
    pub red: u32,
    pub green: u32,
    pub blue: u32,
    pub yellow: u32,
    pub cyan: u32,
    pub magenta: u32,
}
/// `a` weighted `percent`% against `b`, per channel, in integers (palette derivation and faded diff colours).
pub const fn blend(a: u32, b: u32, percent: u32) -> u32 {
    let mut out = 0;
    let mut shift = 0;
    while shift <= 16 {
        out |= ((((a >> shift) & 255) * percent + ((b >> shift) & 255) * (100 - percent)) / 100)
            << shift;
        shift += 8;
    }
    out
}
pub(super) const fn from_seed(s: Seed) -> Palette {
    Palette {
        bg: s.bg,
        fg: s.fg,
        dim: s.muted,
        gutter_bg: s.dark,
        num_fg: s.muted,
        header_bg: s.lighter,
        sidebar_bg: s.dark,
        status_bg: s.lighter,
        border: blend(s.fg, s.bg, 25),
        selected_bg: s.selection,
        fold_bg: s.lighter,
        sel_bg: s.selection,
        caret: s.fg,
        found_bg: blend(s.yellow, s.bg, 25),
        banner_bg: blend(s.yellow, s.bg, 20),
        accent: s.accent,
        error: s.red,
        blame_new: blend(s.blue, s.bg, 30),
        block: [
            blend(s.green, s.bg, 18),
            blend(s.red, s.bg, 18),
            blend(s.blue, s.bg, 18),
            blend(s.yellow, s.bg, 18),
        ],
        inline: [
            blend(s.green, s.bg, 35),
            blend(s.red, s.bg, 35),
            blend(s.blue, s.bg, 35),
            blend(s.yellow, s.bg, 35),
        ],
        edge: [s.green, s.red, s.blue, s.yellow],
        status: [s.green, s.red, s.blue, s.magenta, s.red],
        syntax: Syntax {
            keyword: s.magenta,
            string: s.green,
            number: s.yellow,
            comment: s.muted,
            doc_comment: s.muted,
            function: s.blue,
            constant: s.yellow,
            macro_: s.cyan,
            type_: s.yellow,
            builtin_var: s.red,
            tag: s.blue,
            attribute: s.yellow,
            label: s.cyan,
            link: s.accent,
        },
    }
}
